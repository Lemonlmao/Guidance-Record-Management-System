CREATE TABLE IF NOT EXISTS settings (
    setting_key VARCHAR(80) PRIMARY KEY,
    setting_value VARCHAR(500) NOT NULL
);
CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id VARCHAR(40) NOT NULL UNIQUE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    grade VARCHAR(40) NOT NULL,
    section_name VARCHAR(60) NOT NULL DEFAULT '',
    email VARCHAR(150) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS guidance_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    title VARCHAR(180) NOT NULL,
    category VARCHAR(30) NOT NULL CHECK (category IN ('Academic','Career','Personal','Behavioral','Family','Attendance')),
    priority VARCHAR(10) NOT NULL CHECK (priority IN ('Low','Normal','High')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('Open','In progress','Resolved')),
    opened_on DATE NOT NULL,
    follow_up DATE,
    counselor VARCHAR(120) NOT NULL,
    summary VARCHAR(6000) NOT NULL DEFAULT '',
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS case_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id BIGINT NOT NULL REFERENCES guidance_records(id),
    author VARCHAR(120) NOT NULL,
    body VARCHAR(6000) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    title VARCHAR(180) NOT NULL,
    appointment_date DATE NOT NULL,
    starts_at VARCHAR(5) NOT NULL,
    duration INTEGER NOT NULL CHECK (duration BETWEEN 15 AND 180),
    counselor VARCHAR(120) NOT NULL,
    location_name VARCHAR(120) NOT NULL DEFAULT 'Guidance office',
    status VARCHAR(20) NOT NULL DEFAULT 'Scheduled' CHECK (status IN ('Scheduled','Completed','Cancelled')),
    notes VARCHAR(3000) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_record_student ON guidance_records(student_id);
CREATE INDEX IF NOT EXISTS idx_record_followup ON guidance_records(follow_up);
CREATE INDEX IF NOT EXISTS idx_note_record ON case_notes(record_id);
CREATE INDEX IF NOT EXISTS idx_appointment_day ON appointments(appointment_date);

